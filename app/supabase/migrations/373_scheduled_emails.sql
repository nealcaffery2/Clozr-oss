-- 373: Scheduled emails from the record composer.
--
-- scheduled_emails: an email a rep wrote now that goes out later, the way
-- scheduled_messages (367) holds a text. The same pg_cron kick
-- (scheduled_kick, every minute, only while something is due) calls the
-- scheduled-send edge function, which claims due rows with
-- scheduled_email_claim and sends each through google-sync's send_email as
-- the row's user (their own Gmail, the mailbox guard, read receipts, the
-- communications row), then marks the row sent or errored.
--
-- Idempotent; safe to re-run.

create table if not exists public.scheduled_emails (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.workspaces(id) on delete cascade,
  user_id uuid not null default auth.uid(),
  seller_id bigint references public.sellers(id) on delete set null,
  buyer_id bigint references public.buyers(id) on delete set null,
  "to" text not null,
  cc text,
  bcc text,
  subject text not null,
  html text not null,
  attachments jsonb not null default '[]'::jsonb,
  send_at timestamptz not null,
  status text not null default 'scheduled' check (status in ('scheduled', 'sending', 'sent', 'error', 'cancelled')),
  claimed_at timestamptz,
  sent_communication_id bigint references public.communications(id) on delete set null,
  error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists scheduled_emails_due_idx on public.scheduled_emails (send_at) where status = 'scheduled';
create index if not exists scheduled_emails_ws_idx on public.scheduled_emails (workspace_id, status, send_at);

alter table public.scheduled_emails enable row level security;

drop policy if exists scheduled_emails_members on public.scheduled_emails;
create policy scheduled_emails_members on public.scheduled_emails
  for all to authenticated
  using (workspace_id in (select public.my_workspace_ids()))
  with check (workspace_id in (select public.my_workspace_ids()) and user_id = (select auth.uid()));

grant select, insert, update, delete on public.scheduled_emails to authenticated;

-- Due rows for one tick, claimed so an overlapping tick holds none of them.
create or replace function public.scheduled_email_claim(p_limit integer default 20)
returns setof public.scheduled_emails
language sql
security definer
set search_path = public, pg_temp
as $$
  with due as (
    select id from public.scheduled_emails
     where status = 'scheduled' and send_at <= now()
       and (claimed_at is null or claimed_at < now() - interval '10 minutes')
     order by send_at
     limit p_limit
     for update skip locked
  )
  update public.scheduled_emails m
     set claimed_at = now(), updated_at = now()
    from due
   where m.id = due.id
  returning m.*;
$$;
revoke all on function public.scheduled_email_claim(integer) from public, anon, authenticated;

-- The kick also fires while an email is due (367's text and 368's campaign checks kept).
create or replace function public.scheduled_kick()
returns void
language plpgsql
security definer
set search_path to 'public', 'extensions', 'pg_temp'
as $$
declare v_url text; v_key text;
begin
  if not exists (
    select 1 from public.scheduled_messages
     where status = 'scheduled' and send_at <= now()
       and (claimed_at is null or claimed_at < now() - interval '10 minutes')
  ) and not exists (
    select 1 from public.scheduled_emails
     where status = 'scheduled' and send_at <= now()
       and (claimed_at is null or claimed_at < now() - interval '10 minutes')
  ) and not exists (
    select 1 from public.sms_campaigns where status in ('active', 'scheduled') and coalesce(next_batch_at, start_at, now()) <= now()
  ) then return; end if;
  select decrypted_secret into v_url from vault.decrypted_secrets where name = 'clozr_project_url';
  select decrypted_secret into v_key from vault.decrypted_secrets where name = 'clozr_service_role_key';
  if v_url is null or v_key is null then return; end if;
  perform net.http_post(
    url := rtrim(v_url, '/') || '/functions/v1/scheduled-send',
    headers := jsonb_build_object('Content-Type', 'application/json', 'Authorization', 'Bearer ' || v_key),
    body := '{"action":"tick"}'::jsonb,
    timeout_milliseconds := 5000);
end $$;
revoke all on function public.scheduled_kick() from public, anon, authenticated;
