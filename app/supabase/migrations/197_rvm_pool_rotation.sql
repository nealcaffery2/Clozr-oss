-- 197: rotation for the RVM number pool, with an audit trail and a spending switch.
--
-- The rvm-pool function (daily at 13:37 UTC via pg_cron clozr-rvm-pool-rotate,
-- after number-guard's 13:07 read; an admin can run it from the RVM tab)
-- retires a pool line that went bad (lib/rvm-rotation.ts: spam label, an
-- At risk grade or a guard pause, a Free Caller Registry refusal, or too few
-- A-signed calls). A retired line keeps its number: callbacks to it are still
-- credited (migration 196); it carries no new drops. rvm-tick, the pre-send
-- check and caller-registry leave retired lines out.
--
-- Buying a replacement costs money, so it follows workspaces.settings.rvm_pool.replace:
--   mode 'off' (default) | 'approve' | 'auto', monthly_cap (0 = none), retire_on 'high' | 'medium'.
-- The function also needs RVM_POOL_LIVE_PURCHASES=true to place a real order;
-- without it every purchase is logged as a dry run.
--
-- caller_lines: retired_at, retired_reason, replaces / replaced_by (the
-- other number in a swap). rvm_pool_events: one row per retire, purchase
-- request, purchase, skip, failure, restore, dismissal or policy change. Members
-- read it; the function and the admin RPCs below write it.
--
-- rvm_pool_restore(ws, phone)        admins: put a retired line back in the pool
-- rvm_pool_dismiss(ws, event)        admins: close an open purchase request without buying
-- rvm_pool_set_replace(ws, mode, monthly_cap, retire_on)   admins: the spending switch
-- Safe to run again.

alter table public.caller_lines
  add column if not exists retired_at timestamptz,
  add column if not exists retired_reason text,
  add column if not exists replaces text,
  add column if not exists replaced_by text;

create table if not exists public.rvm_pool_events (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.workspaces(id) on delete cascade,
  phone_e164 text,
  action text not null check (action in (
    'retired', 'restored', 'purchase_requested', 'purchased', 'purchase_skipped', 'purchase_failed', 'dismissed', 'policy_changed')),
  -- open: a purchase request waiting on an admin. done: everything else.
  status text not null default 'done' check (status in ('open', 'done', 'dismissed')),
  reason text,
  detail jsonb not null default '{}'::jsonb,
  actor uuid,
  created_at timestamptz not null default now(),
  resolved_at timestamptz,
  resolved_by uuid
);
create index if not exists rvm_pool_events_ws on public.rvm_pool_events (workspace_id, created_at desc);
create index if not exists rvm_pool_events_open on public.rvm_pool_events (workspace_id) where status = 'open';

alter table public.rvm_pool_events enable row level security;
drop policy if exists rvm_pool_events_read on public.rvm_pool_events;
create policy rvm_pool_events_read on public.rvm_pool_events for select to authenticated
  using (workspace_id in (select public.my_workspace_ids()));
revoke all on public.rvm_pool_events from anon;
grant select on public.rvm_pool_events to authenticated;

create or replace function public.rvm_pool_restore(p_ws bigint, p_phone text)
returns void
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if not public.has_role(p_ws, 'owner', 'admin') then
    raise exception 'admins only' using errcode = '42501';
  end if;
  update public.caller_lines set retired_at = null, retired_reason = null
   where workspace_id = p_ws and phone_e164 = p_phone and retired_at is not null;
  if not found then raise exception 'that line is not retired'; end if;
  insert into public.rvm_pool_events (workspace_id, phone_e164, action, reason, actor)
  values (p_ws, p_phone, 'restored', 'Put back in the pool by an admin', auth.uid());
end $$;
revoke all on function public.rvm_pool_restore(bigint, text) from public, anon;
grant execute on function public.rvm_pool_restore(bigint, text) to authenticated;

create or replace function public.rvm_pool_dismiss(p_ws bigint, p_event bigint)
returns void
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_phone text;
begin
  if not public.has_role(p_ws, 'owner', 'admin') then
    raise exception 'admins only' using errcode = '42501';
  end if;
  update public.rvm_pool_events set status = 'dismissed', resolved_at = now(), resolved_by = auth.uid()
   where id = p_event and workspace_id = p_ws and status = 'open'
  returning phone_e164 into v_phone;
  if not found then raise exception 'no open request with that id'; end if;
  insert into public.rvm_pool_events (workspace_id, phone_e164, action, reason, actor, detail)
  values (p_ws, v_phone, 'dismissed', 'Replacement not bought', auth.uid(), jsonb_build_object('request', p_event));
end $$;
revoke all on function public.rvm_pool_dismiss(bigint, bigint) from public, anon;
grant execute on function public.rvm_pool_dismiss(bigint, bigint) to authenticated;

create or replace function public.rvm_pool_set_replace(p_ws bigint, p_mode text, p_monthly_cap integer, p_retire_on text)
returns void
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_replace jsonb;
begin
  if not public.has_role(p_ws, 'owner', 'admin') then
    raise exception 'admins only' using errcode = '42501';
  end if;
  if coalesce(p_mode, 'off') not in ('off', 'approve', 'auto') then raise exception 'mode must be off, approve or auto'; end if;
  if coalesce(p_retire_on, 'high') not in ('high', 'medium') then raise exception 'retire_on must be high or medium'; end if;
  if p_monthly_cap is not null and (p_monthly_cap < 0 or p_monthly_cap > 50) then raise exception 'monthly cap must be 0 to 50'; end if;
  v_replace := jsonb_build_object('mode', coalesce(p_mode, 'off'), 'monthly_cap', coalesce(p_monthly_cap, 0), 'retire_on', coalesce(p_retire_on, 'high'));
  update public.workspaces
     set settings = jsonb_set(coalesce(settings, '{}'::jsonb), '{rvm_pool}',
                              coalesce(settings -> 'rvm_pool', '{}'::jsonb) || jsonb_build_object('replace', v_replace))
   where id = p_ws;
  insert into public.rvm_pool_events (workspace_id, action, reason, actor, detail)
  values (p_ws, 'policy_changed', 'Replacement settings changed', auth.uid(), v_replace);
end $$;
revoke all on function public.rvm_pool_set_replace(bigint, text, integer, text) from public, anon;
grant execute on function public.rvm_pool_set_replace(bigint, text, integer, text) to authenticated;

create or replace function public.rvm_pool_kick()
returns void
language plpgsql security definer set search_path = public, extensions, pg_temp as $$
declare v_url text; v_key text;
begin
  if not exists (select 1 from public.caller_lines where pool = 'rvm' and retired_at is null) then return; end if;
  select decrypted_secret into v_url from vault.decrypted_secrets where name = 'clozr_project_url';
  select decrypted_secret into v_key from vault.decrypted_secrets where name = 'clozr_service_role_key';
  if v_url is null or v_key is null then return; end if;
  perform net.http_post(
    url := rtrim(v_url, '/') || '/functions/v1/rvm-pool',
    headers := jsonb_build_object('Content-Type', 'application/json', 'Authorization', 'Bearer ' || v_key),
    body := '{"action":"rotate"}'::jsonb,
    timeout_milliseconds := 60000);
end $$;
revoke execute on function public.rvm_pool_kick() from public, anon, authenticated;

select cron.unschedule('clozr-rvm-pool-rotate') where exists (select 1 from cron.job where jobname = 'clozr-rvm-pool-rotate');
select cron.schedule('clozr-rvm-pool-rotate', '37 13 * * *', 'select public.rvm_pool_kick()');
