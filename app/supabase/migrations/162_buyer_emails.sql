-- 162 · A buyer can have more than one email address.
--
-- buyers.email stays the address: what the record shows first, what an email
-- goes to, what dedupe matches on. buyer_emails holds the rest in the order
-- they were added (position 2, 3, …), the way buyer_phones holds the other
-- numbers. The buyer record lists them under the primary, and anyone who can
-- edit buyers adds or removes one.
--
--   buyer_emails   one row per extra address: email as typed, email_key the
--                  lower-cased address (one per buyer), position, kind
--                  (work, personal…), source (manual, skip trace…).
--                  Row security is the buyers rule: the roles that read
--                  buyers read these; owners, admins and dispositions write.

create table if not exists public.buyer_emails (
  id           bigint generated by default as identity primary key,
  workspace_id bigint not null references public.workspaces(id) on delete cascade,
  buyer_id     bigint not null references public.buyers(id) on delete cascade,
  email        text not null,
  email_key    text not null,
  position     smallint not null default 2,
  kind         text,
  source       text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  constraint buyer_emails_email_shape check (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  constraint buyer_emails_key_lower check (email_key = lower(btrim(email)))
);

create unique index if not exists uq_buyer_emails on public.buyer_emails (buyer_id, email_key);
create index if not exists idx_buyer_emails_buyer on public.buyer_emails (buyer_id, position);
create index if not exists idx_buyer_emails_key on public.buyer_emails (workspace_id, email_key);

drop trigger if exists buyer_emails_touch on public.buyer_emails;
create trigger buyer_emails_touch before update on public.buyer_emails
  for each row execute function public.touch_updated_at();

alter table public.buyer_emails enable row level security;

drop policy if exists buyer_emails_select on public.buyer_emails;
create policy buyer_emails_select on public.buyer_emails for select
  using (public.has_role(workspace_id, 'owner', 'admin', 'dispositions', 'tc', 'member'));

drop policy if exists buyer_emails_write on public.buyer_emails;
create policy buyer_emails_write on public.buyer_emails for all
  using (public.has_role(workspace_id, 'owner', 'admin', 'dispositions'))
  with check (public.has_role(workspace_id, 'owner', 'admin', 'dispositions'));
