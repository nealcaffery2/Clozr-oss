-- 150: local presence numbers for the AI agents
-- (docs/voice-agent.md, Local presence numbers).
--
-- voice_agent_numbers  the workspace's pool of AI caller numbers, one per
--                      market: the market's name, state, main area code and
--                      the area codes it is local for (covers), the number,
--                      its label, which agent answers when someone calls it
--                      back, and where it is in buying and wiring
--                      (status wanted → ordered → active, or failed with
--                      error). Every AI call goes out from the number local
--                      to the lead: same area code, else same state, else
--                      the agent's own default. Publish (voice-agent-admin)
--                      buys the wanted numbers in Telnyx, puts them on the
--                      CLOZR AI SIP connection, imports them into ElevenLabs
--                      under their labels and assigns each to its answering
--                      agent. Members read; only the functions write.
-- voice_agent_secrets  gains the Telnyx SIP connection the numbers ride (an
--                      FQDN connection to sip.rtc.elevenlabs.io) and the
--                      credentials ElevenLabs uses to call through it.
--                      Service role only, as before.
--
-- No markets are seeded: a workspace adds its own on the Local numbers
-- screen. Safe to run again.

create table if not exists public.voice_agent_numbers (
  id                 bigint generated by default as identity primary key,
  workspace_id       bigint not null references public.workspaces(id) on delete cascade,
  market             text   not null,
  state              text,
  area_code          text   not null,
  covers             text[] not null default '{}',
  label              text   not null default '',
  answer_agent_key   text,
  phone_number       text,
  status             text   not null default 'wanted',
  telnyx_number_id   text,
  telnyx_order_id    text,
  el_phone_number_id text,
  error              text,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  unique (workspace_id, market)
);

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'voice_agent_numbers_status_check') then
    alter table public.voice_agent_numbers add constraint voice_agent_numbers_status_check
      check (status in ('wanted', 'ordered', 'active', 'failed'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'voice_agent_numbers_area_code_check') then
    alter table public.voice_agent_numbers add constraint voice_agent_numbers_area_code_check
      check (area_code ~ '^[2-9][0-9]{2}$');
  end if;
end $$;
create index if not exists voice_agent_numbers_ws_idx on public.voice_agent_numbers (workspace_id, status);

alter table public.voice_agent_numbers enable row level security;
drop policy if exists voice_agent_numbers_select on public.voice_agent_numbers;
create policy voice_agent_numbers_select on public.voice_agent_numbers
  for select to authenticated
  using (public.is_workspace_member(workspace_id));
revoke insert, update, delete on public.voice_agent_numbers from anon, authenticated;
grant select on public.voice_agent_numbers to authenticated;

alter table public.voice_agent_secrets add column if not exists sip_connection_id text;
alter table public.voice_agent_secrets add column if not exists sip_username text;
alter table public.voice_agent_secrets add column if not exists sip_password text;
