create or replace function public.buyer_buybox_from_area_code(p_ws bigint, p_limit int default 2000)
returns int
language plpgsql
security definer
set search_path = public
as $$
declare
  n int;
begin
  with todo as (
    select b.id, s.state, s.npa
    from public.buyers b
    join public.area_code_states s
      on s.npa = substr(right(regexp_replace(coalesce(b.phone, ''), '\D', '', 'g'), 10), 1, 3)
    where b.workspace_id = p_ws
      and b.archived_at is null
      and length(regexp_replace(coalesce(b.phone, ''), '\D', '', 'g')) >= 10
      and coalesce(cardinality(b.markets), 0) = 0
      and coalesce(jsonb_array_length(case when jsonb_typeof(b.criteria->'location_prefs') = 'array' then b.criteria->'location_prefs' end), 0) = 0
      and coalesce(jsonb_array_length(case when jsonb_typeof(b.criteria->'locations'->'states') = 'array' then b.criteria->'locations'->'states' end), 0) = 0
      and coalesce(jsonb_array_length(case when jsonb_typeof(b.criteria->'locations'->'cities') = 'array' then b.criteria->'locations'->'cities' end), 0) = 0
      and coalesce(jsonb_array_length(case when jsonb_typeof(b.criteria->'locations'->'counties') = 'array' then b.criteria->'locations'->'counties' end), 0) = 0
      and coalesce(jsonb_array_length(case when jsonb_typeof(b.criteria->'locations'->'zips') = 'array' then b.criteria->'locations'->'zips' end), 0) = 0
      and not (coalesce(b.tags, '{}') && array['realtors', 'realtor'])
      and coalesce(b.buyer_type, '') !~* '(agent|realtor)'
      and not exists (select 1 from public.buyer_markets m where m.buyer_id = b.id)
    order by b.id
    limit p_limit
  )
  update public.buyers b
     set criteria = coalesce(b.criteria, '{}'::jsonb)
           || jsonb_build_object(
                'location_prefs', jsonb_build_array(jsonb_build_object('name', t.state, 'type', 'state', 'restricted', false)),
                'locations', coalesce(b.criteria->'locations', '{}'::jsonb) || jsonb_build_object('states', jsonb_build_array(t.state)),
                'location_source', jsonb_build_object('from', 'area_code', 'npa', t.npa, 'state', t.state, 'at', now())),
         markets = array[t.state],
         buy_box = case when coalesce(btrim(b.buy_box), '') = '' then t.state || ' · from phone area code ' || t.npa else t.state || ' · ' || b.buy_box end,
         tags = case when 'area-code-buybox' = any(coalesce(b.tags, '{}')) then b.tags else array_append(coalesce(b.tags, '{}'), 'area-code-buybox'::text) end
    from todo t
   where b.id = t.id;
  get diagnostics n = row_count;
  return n;
end $$;

revoke all on function public.buyer_buybox_from_area_code(bigint, int) from public, anon, authenticated;
