-- 356 · Buy area from the phone's area code, for buyers with none.
--
-- Imported buyers often have
-- no buy area at all: no markets, no buy-box locations, no buyer_markets
-- rows. The matcher scores them 0 for every deal, so no campaign reaches
-- them. Their phone's area code says which state they are in, and the matcher
-- already treats a state as a buy area (lib/buyer-profile scoreBuyerDeal and
-- score_buyer_deal: a deal in that state matches on geography, any other
-- state is refused).
--
-- buyer_buybox_from_area_code(p_ws, p_limit) gives each such buyer one state
-- buy area, written the way the buyer record writes markets
-- (lib/crm-write saveBuyerField): criteria.location_prefs, the state in
-- criteria.locations, markets, and buy_box when it is empty. The area code is
-- kept on criteria.location_source and the buyer is tagged area-code-buybox,
-- so the inferred ones are easy to find and the first real buy area a rep
-- types replaces it. A buyer with any buy area, a realtor, an archived row or
-- a phone outside the US map is left alone. Area codes by state: the NANPA
-- table in lib/rvm-pool.ts (overlays included).
--
-- Idempotent: a buyer it filled now has a buy area, so a re-run skips them.

create table if not exists public.area_code_states (
  npa text primary key,
  state text not null
);
alter table public.area_code_states enable row level security;
drop policy if exists area_code_states_read on public.area_code_states;
create policy area_code_states_read on public.area_code_states for select to authenticated using (true);

