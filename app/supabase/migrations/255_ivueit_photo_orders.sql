-- iVueit photo orders: a Vuer shoots the house, the photos land on the deal.
--
-- The workspace's iVueit API key and secret (Client Portal) are write-only,
-- like the InvestorBase key (92): only the ivueit edge function reads them
-- with the service role. The base URL is staging while we test and
-- production after; the survey template is the job a Vuer runs.
--
-- photo_orders is one row per Vue: ordered from the deal sheet or TC file,
-- completed when iVueit's VueCompleted webhook (or the 20-minute sweep, or a
-- person's Check now) finds a submission; its photos are copied into the
-- deal-files bucket as deal_files rows with source 'ivueit'.

alter table public.workspace_integration_secrets add column if not exists ivueit_api_key text;
alter table public.workspace_integration_secrets add column if not exists ivueit_secret text;
alter table public.workspace_integration_secrets add column if not exists ivueit_base_url text;
alter table public.workspace_integration_secrets add column if not exists ivueit_template_id text;
alter table public.workspace_integration_secrets add column if not exists ivueit_hook_token text;

create table if not exists public.photo_orders (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.workspaces(id) on delete cascade,
  deal_id bigint not null references public.deals(id) on delete cascade,
  provider text not null default 'ivueit' check (provider in ('ivueit')),
  vue_id text,
  status text not null default 'ordered' check (status in ('ordered', 'completed', 'canceled', 'failed')),
  address text,
  template_id text,
  notes text,
  urgent boolean not null default false,
  submission_id text,
  photo_count integer not null default 0,
  cost numeric,
  error text,
  ordered_by uuid,
  created_at timestamptz not null default now(),
  checked_at timestamptz,
  completed_at timestamptz
);
create unique index if not exists photo_orders_vue_uidx on public.photo_orders (provider, vue_id) where vue_id is not null;
create index if not exists photo_orders_deal_idx on public.photo_orders (deal_id, created_at desc);
create index if not exists photo_orders_open_idx on public.photo_orders (workspace_id) where status = 'ordered';

alter table public.photo_orders enable row level security;
drop policy if exists photo_orders_select on public.photo_orders;
create policy photo_orders_select on public.photo_orders for select to authenticated
  using ((select public.is_workspace_member(workspace_id)));
-- Writes go through the ivueit edge function only.
revoke insert, update, delete on public.photo_orders from anon, authenticated;
grant select on public.photo_orders to authenticated;

-- Key and secret together; an empty key disconnects. Base URL and template
-- are settings, saved with the same call (null keeps what is there).
create or replace function public.set_ivueit_keys(
  p_workspace_id bigint, p_key text, p_secret text, p_base_url text default null, p_template_id text default null
) returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  k text := nullif(btrim(coalesce(p_key, '')), '');
  s text := nullif(btrim(coalesce(p_secret, '')), '');
  u text := nullif(rtrim(btrim(coalesce(p_base_url, '')), '/'), '');
  t text := nullif(btrim(coalesce(p_template_id, '')), '');
begin
  if not public.has_role(p_workspace_id, 'owner', 'admin') then
    raise exception 'only an owner or admin can save the iVueit keys' using errcode = '42501';
  end if;
  if p_key is not null and k is not null and (length(k) < 8 or length(k) > 400) then
    raise exception 'that does not look like an iVueit API key' using errcode = '22023';
  end if;
  if p_secret is not null and s is not null and (length(s) < 8 or length(s) > 400) then
    raise exception 'that does not look like an iVueit secret' using errcode = '22023';
  end if;
  if u is not null and u !~ '^https://[a-z0-9.-]+(:[0-9]+)?(/[A-Za-z0-9._/-]*)?$' then
    raise exception 'the iVueit URL must be an https address' using errcode = '22023';
  end if;
  if t is not null and length(t) > 80 then
    raise exception 'that does not look like an iVueit survey template id' using errcode = '22023';
  end if;
  insert into public.workspace_integration_secrets (workspace_id, ivueit_api_key, ivueit_secret, ivueit_base_url, ivueit_template_id, ivueit_hook_token)
  values (p_workspace_id, k, s, u, t, encode(extensions.gen_random_bytes(24), 'hex'))
  on conflict (workspace_id) do update set
    -- p_key '' disconnects (both go); null leaves the saved pair alone.
    ivueit_api_key = case when p_key is null then workspace_integration_secrets.ivueit_api_key else k end,
    ivueit_secret = case when p_key is not null and k is null then null when p_secret is null then workspace_integration_secrets.ivueit_secret else s end,
    ivueit_base_url = case when p_base_url is null then workspace_integration_secrets.ivueit_base_url else u end,
    ivueit_template_id = case when p_template_id is null then workspace_integration_secrets.ivueit_template_id else t end,
    ivueit_hook_token = coalesce(workspace_integration_secrets.ivueit_hook_token, excluded.ivueit_hook_token),
    updated_at = now();
  perform public.audit_event(p_workspace_id, 'ivueit.keys', jsonb_build_object(
    'connected', (select length(coalesce(ivueit_api_key, '')) >= 8 and length(coalesce(ivueit_secret, '')) >= 8
                    from public.workspace_integration_secrets where workspace_id = p_workspace_id)));
end $$;
revoke all on function public.set_ivueit_keys(bigint, text, text, text, text) from public, anon;
grant execute on function public.set_ivueit_keys(bigint, text, text, text, text) to authenticated;

-- What a member may know: connected or not, which URL, which template. Never the key.
create or replace function public.ivueit_settings(p_workspace_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare r record;
begin
  if not public.is_workspace_member(p_workspace_id) then
    raise exception 'not a member of that workspace' using errcode = '42501';
  end if;
  select ivueit_api_key, ivueit_secret, ivueit_base_url, ivueit_template_id into r
    from public.workspace_integration_secrets where workspace_id = p_workspace_id;
  return jsonb_build_object(
    'connected', coalesce(length(coalesce(r.ivueit_api_key, '')) >= 8 and length(coalesce(r.ivueit_secret, '')) >= 8, false),
    'base_url', r.ivueit_base_url,
    'template_id', r.ivueit_template_id);
end $$;
revoke all on function public.ivueit_settings(bigint) from public, anon;
grant execute on function public.ivueit_settings(bigint) to authenticated;

-- The sweep behind the webhook: every open order older than five minutes
-- gets checked, so a missed webhook costs at most twenty minutes.
create or replace function public.ivueit_sweep_kick()
returns integer language plpgsql security definer set search_path = public, extensions as $$
declare v_url text; v_key text; w record; n integer := 0;
begin
  select decrypted_secret into v_url from vault.decrypted_secrets where name = 'clozr_project_url';
  select decrypted_secret into v_key from vault.decrypted_secrets where name = 'clozr_service_role_key';
  if v_url is null or v_key is null then return 0; end if;
  for w in
    select distinct workspace_id from public.photo_orders
    where status = 'ordered' and created_at < now() - interval '5 minutes'
  loop
    perform net.http_post(
      url := rtrim(v_url, '/') || '/functions/v1/ivueit',
      headers := jsonb_build_object('Content-Type', 'application/json', 'Authorization', 'Bearer ' || v_key),
      body := jsonb_build_object('action', 'sweep', 'workspace_id', w.workspace_id),
      timeout_milliseconds := 150000);
    n := n + 1;
  end loop;
  return n;
end $$;
revoke execute on function public.ivueit_sweep_kick() from public, anon, authenticated;

select cron.unschedule('clozr-ivueit-sweep') where exists (select 1 from cron.job where jobname = 'clozr-ivueit-sweep');
select cron.schedule('clozr-ivueit-sweep', '7,27,47 * * * *', 'select public.ivueit_sweep_kick()');
