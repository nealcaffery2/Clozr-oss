-- 368: Bulk SMS campaigns (SmarterContact-style), delivered through 367's
-- scheduled_messages.
--
-- sms_campaigns: name, status, the audience it was built from, the rotating
-- templates and lines, the start, the batch cadence, the delivery window in
-- the recipient's local time, and what to do when nobody replies.
-- sms_campaign_recipients: one row per seller and number; pending until the
-- expander (scheduled-send, action expand) writes its scheduled_messages row,
-- then scheduled / sent / error / responded / no_reply / cancelled.
--
-- sms_campaign_fill(campaign, seller ids, dry) materialises recipients with
-- the send-safety exclusions (DNC and blacklist tags, per-number dnc / wrong /
-- landline flags, opted-out threads, no number, duplicates) and reports the
-- counts, so the editor shows them before anything is scheduled.
--
-- Replies: an inbound SMS communications row marks the recipient responded
-- and cancels its scheduled_messages row. The scheduled row's status flows
-- back to the recipient and the campaign counts by trigger.
--
-- scheduled_kick() (367) also fires when a campaign batch is due, so the
-- existing per-minute cron is the only scheduler.
--
-- Idempotent; safe to re-run.

create table if not exists public.sms_campaigns (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.workspaces(id) on delete cascade,
  created_by uuid not null default auth.uid(),
  name text not null check (length(trim(name)) between 1 and 120),
  status text not null default 'draft' check (status in ('draft', 'scheduled', 'active', 'paused', 'completed')),
  audience jsonb not null default '{}'::jsonb,
  template_ids bigint[] not null default '{}',
  from_numbers text[] not null default '{}',
  tz text not null default 'America/Chicago',
  start_at timestamptz,
  send_all_at_once boolean not null default false,
  batch_size integer not null default 100 check (batch_size between 1 and 5000),
  batch_every_minutes integer not null default 30 check (batch_every_minutes between 1 and 1440),
  window_start integer not null default 9 check (window_start between 0 and 23),
  window_end integer not null default 20 check (window_end between 1 and 24),
  window_days integer[] not null default '{1,2,3,4,5,6}',
  reply_action jsonb not null default '{}'::jsonb,
  parent_id bigint references public.sms_campaigns(id) on delete set null,
  next_batch_at timestamptz,
  total_count integer not null default 0,
  sent_count integer not null default 0,
  failed_count integer not null default 0,
  responded_count integer not null default 0,
  excluded jsonb not null default '{}'::jsonb,
  last_sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists sms_campaigns_ws_idx on public.sms_campaigns (workspace_id, status, created_at desc);
create index if not exists sms_campaigns_due_idx on public.sms_campaigns (next_batch_at) where status = 'active';

alter table public.sms_campaigns enable row level security;
drop policy if exists sms_campaigns_members on public.sms_campaigns;
create policy sms_campaigns_members on public.sms_campaigns
  for all to authenticated
  using (workspace_id in (select public.my_workspace_ids()))
  with check (workspace_id in (select public.my_workspace_ids()));
grant select, insert, update, delete on public.sms_campaigns to authenticated;

create table if not exists public.sms_campaign_recipients (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references public.sms_campaigns(id) on delete cascade,
  workspace_id bigint not null references public.workspaces(id) on delete cascade,
  seller_id bigint references public.sellers(id) on delete cascade,
  phone text not null,
  phone_key text,
  state text,
  template_id bigint,
  from_number text,
  scheduled_for timestamptz,
  status text not null default 'pending' check (status in ('pending', 'scheduled', 'sent', 'error', 'responded', 'no_reply', 'cancelled')),
  scheduled_message_id bigint references public.scheduled_messages(id) on delete set null,
  communication_id bigint references public.communications(id) on delete set null,
  error text,
  sent_at timestamptz,
  responded_at timestamptz,
  created_at timestamptz not null default now(),
  constraint sms_campaign_recipients_once unique (campaign_id, phone)
);
create index if not exists sms_campaign_recipients_pending_idx on public.sms_campaign_recipients (campaign_id, status, id);
create index if not exists sms_campaign_recipients_phone_idx on public.sms_campaign_recipients (workspace_id, phone_key) where status in ('pending', 'scheduled', 'sent');
create index if not exists sms_campaign_recipients_sched_idx on public.sms_campaign_recipients (scheduled_message_id) where scheduled_message_id is not null;

alter table public.sms_campaign_recipients enable row level security;
drop policy if exists sms_campaign_recipients_members on public.sms_campaign_recipients;
create policy sms_campaign_recipients_members on public.sms_campaign_recipients
  for all to authenticated
  using (workspace_id in (select public.my_workspace_ids()))
  with check (workspace_id in (select public.my_workspace_ids()));
grant select, insert, update, delete on public.sms_campaign_recipients to authenticated;

-- Recipients for a campaign from seller ids, with the exclusions counted.
-- p_dry only counts. Returns {added, no_phone, dnc, blacklisted, opted_out,
-- wrong_number, landline, duplicate}.
create or replace function public.sms_campaign_fill(p_campaign bigint, p_seller_ids bigint[], p_dry boolean default false)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_ws bigint;
  v_out jsonb;
begin
  select workspace_id into v_ws from public.sms_campaigns where id = p_campaign;
  if v_ws is null or v_ws not in (select public.my_workspace_ids()) then
    raise exception 'campaign not found';
  end if;
  create temp table if not exists _fill (seller_id bigint, phone text, phone_key text, state text, why text) on commit drop;
  delete from _fill;
  insert into _fill
  select s.id, n.phone, public.normalize_phone(n.phone),
         (select p.state from public.properties p where p.id = s.property_id),
         case
           when n.phone is null then 'no_phone'
           when exists (select 1 from unnest(coalesce(s.tags, '{}')) t where t = 'secret-blacklist') then 'blacklisted'
           when exists (select 1 from unnest(coalesce(s.tags, '{}')) t where t ~* '^(dnc|do.?not.?call)$') then 'dnc'
           when sp.is_dnc then 'dnc'
           when sp.is_wrong then 'wrong_number'
           when sp.kind = 'landline' then 'landline'
           when exists (select 1 from public.inbox_threads it where it.workspace_id = v_ws and it.phone_key = public.normalize_phone(n.phone) and it.opted_out_at is not null) then 'opted_out'
           when exists (select 1 from public.sms_campaign_recipients r where r.campaign_id = p_campaign and r.phone = n.phone) then 'duplicate'
           else 'ok'
         end
    from public.sellers s
    cross join lateral (
      select case when length(regexp_replace(coalesce(s.phone, ''), '\D', '', 'g')) >= 10
                  then '+1' || right(regexp_replace(s.phone, '\D', '', 'g'), 10) end as phone
    ) n
    left join public.seller_phones sp on sp.seller_id = s.id and sp.phone = n.phone
   where s.workspace_id = v_ws and s.id = any(p_seller_ids);
  -- Two sellers on one number: the first keeps it.
  update _fill f set why = 'duplicate'
   where why = 'ok' and exists (select 1 from _fill g where g.why = 'ok' and g.phone = f.phone and g.seller_id < f.seller_id);
  select coalesce(jsonb_object_agg(why, n), '{}'::jsonb) into v_out
    from (select case when why = 'ok' then 'added' else why end why, count(*) n from _fill group by 1) x;
  if not p_dry then
    insert into public.sms_campaign_recipients (campaign_id, workspace_id, seller_id, phone, phone_key, state)
    select p_campaign, v_ws, seller_id, phone, phone_key, state from _fill where why = 'ok'
    on conflict (campaign_id, phone) do nothing;
    update public.sms_campaigns c
       set total_count = (select count(*) from public.sms_campaign_recipients r where r.campaign_id = c.id),
           excluded = v_out - 'added', updated_at = now()
     where c.id = p_campaign;
  end if;
  return v_out;
end $$;
grant execute on function public.sms_campaign_fill(bigint, bigint[], boolean) to authenticated;

-- A scheduled row's fate flows to its recipient and the campaign counts.
create or replace function public.sms_campaign_recipient_sync()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare v_cid bigint;
begin
  if new.status = old.status then return new; end if;
  update public.sms_campaign_recipients r
     set status = case new.status when 'sent' then 'sent' when 'error' then 'error' when 'cancelled' then 'cancelled' else r.status end,
         communication_id = coalesce(new.sent_communication_id, r.communication_id),
         error = case when new.status = 'error' then new.error else r.error end,
         sent_at = case when new.status = 'sent' then now() else r.sent_at end
   where r.scheduled_message_id = new.id and r.status in ('pending', 'scheduled')
   returning r.campaign_id into v_cid;
  if v_cid is not null then
    update public.sms_campaigns c
       set sent_count = (select count(*) from public.sms_campaign_recipients r where r.campaign_id = c.id and r.status in ('sent', 'responded', 'no_reply')),
           failed_count = (select count(*) from public.sms_campaign_recipients r where r.campaign_id = c.id and r.status = 'error'),
           last_sent_at = case when new.status = 'sent' then now() else c.last_sent_at end,
           updated_at = now()
     where c.id = v_cid;
  end if;
  return new;
end $$;
drop trigger if exists sms_campaign_recipient_sync on public.scheduled_messages;
create trigger sms_campaign_recipient_sync after update of status on public.scheduled_messages
  for each row execute function public.sms_campaign_recipient_sync();

-- A reply from a recipient: responded, and nothing more goes to them from
-- any campaign that still has them pending.
create or replace function public.sms_campaign_on_reply()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare v_key text;
begin
  if new.direction <> 'inbound' or new.channel <> 'sms' or new.from_phone is null then return new; end if;
  v_key := public.normalize_phone(new.from_phone);
  update public.scheduled_messages m set status = 'cancelled', error = 'They replied', updated_at = now()
   where m.status = 'scheduled'
     and m.id in (select r.scheduled_message_id from public.sms_campaign_recipients r
                   where r.workspace_id = new.workspace_id and r.phone_key = v_key and r.status = 'scheduled');
  with hit as (
    update public.sms_campaign_recipients r
       set status = 'responded', responded_at = new.occurred_at
     where r.workspace_id = new.workspace_id and r.phone_key = v_key and r.status in ('pending', 'scheduled', 'sent')
     returning r.campaign_id
  )
  update public.sms_campaigns c
     set responded_count = (select count(*) from public.sms_campaign_recipients r where r.campaign_id = c.id and r.status = 'responded'),
         updated_at = now()
   where c.id in (select campaign_id from hit);
  return new;
end $$;
drop trigger if exists sms_campaign_on_reply on public.communications;
create trigger sms_campaign_on_reply after insert on public.communications
  for each row execute function public.sms_campaign_on_reply();

-- Pausing or deleting a campaign pulls back what has not gone out.
create or replace function public.sms_campaign_cancel_pending(p_campaign bigint)
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare n integer;
begin
  if (select workspace_id from public.sms_campaigns where id = p_campaign) not in (select public.my_workspace_ids()) then
    raise exception 'campaign not found';
  end if;
  update public.scheduled_messages m set status = 'cancelled', error = 'Campaign paused', updated_at = now()
   where m.status = 'scheduled'
     and m.id in (select scheduled_message_id from public.sms_campaign_recipients where campaign_id = p_campaign and status = 'scheduled');
  get diagnostics n = row_count;
  update public.sms_campaign_recipients set status = 'pending', scheduled_message_id = null, scheduled_for = null
   where campaign_id = p_campaign and status in ('scheduled', 'cancelled');
  return n;
end $$;
grant execute on function public.sms_campaign_cancel_pending(bigint) to authenticated;

-- The kick also runs when a campaign batch is due.
create or replace function public.scheduled_kick()
returns void
language plpgsql
security definer
set search_path to 'public', 'extensions', 'pg_temp'
as $$
declare v_url text; v_key text;
begin
  if not exists (
    select 1 from public.scheduled_messages
     where status = 'scheduled' and send_at <= now()
       and (claimed_at is null or claimed_at < now() - interval '10 minutes')
  ) and not exists (
    select 1 from public.sms_campaigns where status in ('active', 'scheduled') and coalesce(next_batch_at, start_at, now()) <= now()
  ) then return; end if;
  select decrypted_secret into v_url from vault.decrypted_secrets where name = 'clozr_project_url';
  select decrypted_secret into v_key from vault.decrypted_secrets where name = 'clozr_service_role_key';
  if v_url is null or v_key is null then return; end if;
  perform net.http_post(
    url := rtrim(v_url, '/') || '/functions/v1/scheduled-send',
    headers := jsonb_build_object('Content-Type', 'application/json', 'Authorization', 'Bearer ' || v_key),
    body := '{"action":"tick"}'::jsonb,
    timeout_milliseconds := 5000);
end $$;
revoke all on function public.scheduled_kick() from public, anon, authenticated;
