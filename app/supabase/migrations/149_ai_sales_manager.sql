-- 149: the AI Sales Manager (docs/ai-sales-manager.md).
--
-- Call reviews need no new column: the acquisitions framework, the missed-deal
-- flags and the timed insights ride inside communications.coaching_review
-- (migration 89), written by call-coach and call-sync. This adds:
--
--   roleplay_sessions      one practice session per row: the persona, the
--                          difficulty, the objection drill, voice or text, the
--                          transcript, and the feedback (the same scorecard a
--                          real call gets, plus objection handling and a model
--                          answer). Reps read their own; owners and admins read
--                          the workspace's. Written only by the roleplay
--                          function (service role).
--   sales_coach_settings   per workspace: the ElevenLabs roleplay agent id, and
--                          the weekly scorecard email (on/off, recipients,
--                          when, last run). Members read; owners and admins
--                          write. report-mail's hourly tick sends the email.
--   call_review_submissions  "Submit a call for review": a transcript (.txt)
--                          or a recording (mp3 / wav / m4a, 25 MB) from outside
--                          CLOZR, with its call scoring type, graded the same
--                          way as a recorded call. The audio is uploaded to the
--                          private call-recordings bucket under
--                          <workspace>/uploads/ (members may insert there).
--   communications_flagged_idx  the Flagged calls list's read.
--
-- Roleplay by phone: a rep arms a session (mode 'phone', status 'armed'),
-- then calls the workspace's roleplay line; the ElevenLabs roleplay agent
-- answers as that persona (voice-agent's initiation webhook) and the
-- transcript is graded from its post-call webhook.
-- sales_coach_settings.roleplay_phone is the number shown to reps.
--
-- Safe to run again.

create table if not exists public.roleplay_sessions (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.workspaces(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  persona text not null,
  difficulty text not null default 'medium',
  objection text,
  mode text not null default 'text',
  status text not null default 'active',
  conversation_id text,
  transcript jsonb not null default '[]'::jsonb,
  feedback jsonb,
  score integer,
  stage_hit_rate integer,
  duration_s integer,
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  updated_at timestamptz not null default now()
);

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'roleplay_sessions_mode_check') then
    alter table public.roleplay_sessions add constraint roleplay_sessions_mode_check check (mode in ('voice', 'text', 'phone'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'roleplay_sessions_status_check') then
    alter table public.roleplay_sessions add constraint roleplay_sessions_status_check check (status in ('armed', 'active', 'scored', 'failed', 'abandoned'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'roleplay_sessions_difficulty_check') then
    alter table public.roleplay_sessions add constraint roleplay_sessions_difficulty_check check (difficulty in ('easy', 'medium', 'hard'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'roleplay_sessions_score_check') then
    alter table public.roleplay_sessions add constraint roleplay_sessions_score_check check (score is null or score between 0 and 100);
  end if;
end $$;

create index if not exists roleplay_sessions_ws_user_idx on public.roleplay_sessions (workspace_id, user_id, started_at desc);
create index if not exists roleplay_sessions_ws_started_idx on public.roleplay_sessions (workspace_id, started_at desc);
create index if not exists roleplay_sessions_conversation_idx on public.roleplay_sessions (conversation_id) where conversation_id is not null;
create index if not exists roleplay_sessions_armed_idx on public.roleplay_sessions (workspace_id, user_id) where status = 'armed';

alter table public.roleplay_sessions enable row level security;
drop policy if exists roleplay_sessions_select on public.roleplay_sessions;
create policy roleplay_sessions_select on public.roleplay_sessions for select
  using (
    (user_id = auth.uid() and public.is_workspace_member(workspace_id))
    or public.has_role(workspace_id, 'owner', 'admin')
  );
revoke insert, update, delete on public.roleplay_sessions from anon, authenticated;
grant select on public.roleplay_sessions to authenticated;

create table if not exists public.sales_coach_settings (
  workspace_id bigint primary key references public.workspaces(id) on delete cascade,
  roleplay_agent_id text,
  -- The roleplay phone line reps call (display; the number itself is routed to
  -- the roleplay agent in ElevenLabs).
  roleplay_phone text,
  weekly_email boolean not null default true,
  -- Empty means every owner and admin of the workspace.
  weekly_recipients text[] not null default '{}',
  weekly_at time not null default '08:00',
  weekly_tz text not null default 'America/Chicago',
  next_weekly_at timestamptz,
  last_weekly_at timestamptz,
  last_weekly_error text,
  updated_at timestamptz not null default now()
);

alter table public.sales_coach_settings enable row level security;
drop policy if exists sales_coach_settings_select on public.sales_coach_settings;
create policy sales_coach_settings_select on public.sales_coach_settings for select
  using (public.is_workspace_member(workspace_id));
drop policy if exists sales_coach_settings_write on public.sales_coach_settings;
create policy sales_coach_settings_write on public.sales_coach_settings for all
  using (public.has_role(workspace_id, 'owner', 'admin'))
  with check (public.has_role(workspace_id, 'owner', 'admin'));
grant select, insert, update on public.sales_coach_settings to authenticated;

alter table public.sales_coach_settings add column if not exists roleplay_phone text;

-- Calls from outside CLOZR, submitted for review.
create table if not exists public.call_review_submissions (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.workspaces(id) on delete cascade,
  -- Who submitted it, and whose call it is (the same person unless an admin submitted for a rep).
  user_id uuid not null references auth.users(id) on delete cascade,
  rep_id uuid references auth.users(id) on delete set null,
  call_type text not null default 'seller_acquisitions',
  title text,
  source text not null,
  file_path text,
  transcript text,
  transcript_segments jsonb,
  duration_s integer,
  status text not null default 'processing',
  error text,
  review jsonb,
  score integer,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'call_review_submissions_type_check') then
    alter table public.call_review_submissions add constraint call_review_submissions_type_check
      check (call_type in ('seller_acquisitions', 'seller_follow_up', 'buyer_dispositions'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'call_review_submissions_source_check') then
    alter table public.call_review_submissions add constraint call_review_submissions_source_check check (source in ('text', 'audio'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'call_review_submissions_status_check') then
    alter table public.call_review_submissions add constraint call_review_submissions_status_check check (status in ('processing', 'scored', 'failed'));
  end if;
end $$;
create index if not exists call_review_submissions_ws_idx on public.call_review_submissions (workspace_id, created_at desc);

alter table public.call_review_submissions enable row level security;
drop policy if exists call_review_submissions_select on public.call_review_submissions;
create policy call_review_submissions_select on public.call_review_submissions for select
  using (
    ((user_id = auth.uid() or rep_id = auth.uid()) and public.is_workspace_member(workspace_id))
    or public.has_role(workspace_id, 'owner', 'admin')
  );
revoke insert, update, delete on public.call_review_submissions from anon, authenticated;
grant select on public.call_review_submissions to authenticated;

-- Members upload a recording for review into <workspace>/uploads/ of the
-- private call-recordings bucket (read is already members-only, migration 67).
drop policy if exists "call recordings: members upload for review" on storage.objects;
create policy "call recordings: members upload for review" on storage.objects for insert to authenticated
  with check (
    bucket_id = 'call-recordings'
    and split_part(name, '/', 2) = 'uploads'
    and exists (
      select 1 from public.workspace_members m
      where m.user_id = auth.uid() and m.workspace_id::text = split_part(name, '/', 1)
    )
  );

-- The Flagged calls list: graded calls with at least one flag, newest first.
create index if not exists communications_flagged_idx
  on public.communications (workspace_id, occurred_at desc)
  where coaching_review ? 'flag_ids' and coaching_review -> 'flag_ids' <> '[]'::jsonb;
