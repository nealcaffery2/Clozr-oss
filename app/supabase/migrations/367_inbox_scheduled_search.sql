-- 367: Inbox scheduled texts and message-content search.
--
-- scheduled_messages: a text a rep wrote now that goes out later. Talkr has
-- no send-at on POST /v1/messages, so a pg_cron kick every minute calls the
-- scheduled-send edge function, which sends due rows through textRecipient
-- (carrier wording, blacklist, Talkr's opt-out and quiet hours) and marks each
-- row sent (with the communications id) or errored.
--
-- inbox_search: threads whose texts mention a phrase, on the GIN index that
-- 277 built over comm_search_doc (English stemming: selling matches sells and
-- seller). Returns the counterpart's number, how many texts matched and one
-- highlighted snippet; the Inbox keeps its folder and owner filters on top.
--
-- Idempotent; safe to re-run.

create table if not exists public.scheduled_messages (
  id bigint generated by default as identity primary key,
  workspace_id bigint not null references public.workspaces(id) on delete cascade,
  user_id uuid not null default auth.uid(),
  seller_id bigint references public.sellers(id) on delete set null,
  buyer_id bigint references public.buyers(id) on delete set null,
  phone text not null,
  from_phone_number_id text,
  body text not null,
  media jsonb not null default '[]'::jsonb,
  send_at timestamptz not null,
  status text not null default 'scheduled' check (status in ('scheduled', 'sending', 'sent', 'error', 'cancelled')),
  claimed_at timestamptz,
  sent_communication_id bigint references public.communications(id) on delete set null,
  error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists scheduled_messages_due_idx on public.scheduled_messages (send_at) where status = 'scheduled';
create index if not exists scheduled_messages_ws_idx on public.scheduled_messages (workspace_id, status, send_at);

alter table public.scheduled_messages enable row level security;

drop policy if exists scheduled_messages_members on public.scheduled_messages;
create policy scheduled_messages_members on public.scheduled_messages
  for all to authenticated
  using (workspace_id in (select public.my_workspace_ids()))
  with check (workspace_id in (select public.my_workspace_ids()) and user_id = (select auth.uid()));

grant select, insert, update, delete on public.scheduled_messages to authenticated;

-- Due rows for one tick, claimed so an overlapping tick holds none of them.
-- A claim older than 10 minutes is free again (the tick died).
create or replace function public.scheduled_claim(p_limit integer default 20)
returns setof public.scheduled_messages
language sql
security definer
set search_path = public, pg_temp
as $$
  with due as (
    select id from public.scheduled_messages
     where status = 'scheduled' and send_at <= now()
       and (claimed_at is null or claimed_at < now() - interval '10 minutes')
     order by send_at
     limit p_limit
     for update skip locked
  )
  update public.scheduled_messages m
     set claimed_at = now(), updated_at = now()
    from due
   where m.id = due.id
  returning m.*;
$$;
revoke all on function public.scheduled_claim(integer) from public, anon, authenticated;

create or replace function public.scheduled_kick()
returns void
language plpgsql
security definer
set search_path to 'public', 'extensions', 'pg_temp'
as $$
declare v_url text; v_key text;
begin
  if not exists (
    select 1 from public.scheduled_messages
     where status = 'scheduled' and send_at <= now()
       and (claimed_at is null or claimed_at < now() - interval '10 minutes')
  ) then return; end if;
  select decrypted_secret into v_url from vault.decrypted_secrets where name = 'clozr_project_url';
  select decrypted_secret into v_key from vault.decrypted_secrets where name = 'clozr_service_role_key';
  if v_url is null or v_key is null then return; end if;
  perform net.http_post(
    url := rtrim(v_url, '/') || '/functions/v1/scheduled-send',
    headers := jsonb_build_object('Content-Type', 'application/json', 'Authorization', 'Bearer ' || v_key),
    body := '{"action":"tick"}'::jsonb,
    timeout_milliseconds := 5000);
end $$;
revoke all on function public.scheduled_kick() from public, anon, authenticated;

select cron.unschedule('clozr-scheduled-send') where exists (select 1 from cron.job where jobname = 'clozr-scheduled-send');
select cron.schedule('clozr-scheduled-send', '* * * * *', 'select public.scheduled_kick()');

-- Threads whose texts mention p_q. The counterpart is to_phone on an
-- outbound row and from_phone on an inbound one. Campaign, sequence and
-- AI-agent texts are outbound Talkr rows no person sent (talkr_user_id is
-- null) or rows an agent or a ringless drop wrote; p_campaign includes them.
create or replace function public.inbox_search(p_ws bigint, p_q text, p_campaign boolean default false, p_limit integer default 200)
returns table (phone text, hits integer, last_at timestamptz, snippet text)
language sql
stable
security invoker
set search_path = public, pg_temp
as $$
  with q as (select websearch_to_tsquery('english', coalesce(p_q, '')) tsq),
  hit as (
    select case when c.direction = 'outbound' then c.to_phone else c.from_phone end as phone, c.body, c.occurred_at
      from public.communications c, q
     where c.workspace_id = p_ws and c.channel = 'sms'
       and public.comm_search_doc(c.subject, c.summary, c.body, c.transcript) @@ q.tsq
       and (p_campaign or not (
         (c.direction = 'outbound' and c.source = 'talkr' and c.talkr_user_id is null)
         or c.ai_agent_key is not null or c.rvm_drop_id is not null))
  ),
  ranked as (
    select h.*, row_number() over (partition by h.phone order by h.occurred_at desc) rn, count(*) over (partition by h.phone) n
      from hit h where h.phone is not null
  )
  select r.phone, r.n::integer, r.occurred_at,
         ts_headline('english', r.body, q.tsq, 'MaxFragments=1, MaxWords=18, MinWords=8, StartSel=<mark>, StopSel=</mark>')
    from ranked r, q
   where r.rn = 1 and numnode(q.tsq) > 0
   order by r.occurred_at desc
   limit p_limit;
$$;
grant execute on function public.inbox_search(bigint, text, boolean, integer) to authenticated;
